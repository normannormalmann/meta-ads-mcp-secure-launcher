def t(lang, key, **values):
    text = MESSAGES.get(lang, MESSAGES[DEFAULT_LANGUAGE])[key]
    return text.format(**values) if values else text


def detect_language(requested=None, environ=None, system_locale=None):
    environ = os.environ if environ is None else environ
    for candidate in (requested, environ.get(LANG_ENV)):
        if candidate and candidate.lower() in LANGUAGES:
            return candidate.lower()
    if system_locale is None:
        system_locale = locale.getlocale()[0] or ""
    return "de" if system_locale.lower().startswith(("de", "german")) else DEFAULT_LANGUAGE


def add_language_argument(parser):
    parser.add_argument("--lang", choices=LANGUAGES, help="output language (default: system language)")
